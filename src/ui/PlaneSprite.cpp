Dir fromHeading(float headingDeg) {
    float h = fmod(headingDeg, 360.0f);
    if (h < 0) h += 360.0f;

    if (h < 22.5f || h >= 337.5f) return N;
    if (h < 67.5f)  return NE;
    if (h < 112.5f) return E;
    if (h < 157.5f) return SE;
    if (h < 202.5f) return S;
    if (h < 247.5f) return SW;
    if (h < 292.5f) return W;
    return NW;
}

const uint8_t* large(Dir d) {
    switch (d) {
        case N:  return planeBitmapN;
        case NE: return planeBitmapNE;
        case E:  return planeBitmapE;
        case SE: return planeBitmapSE;
        case S:  return planeBitmapS;
        case SW: return planeBitmapSW;
        case W:  return planeBitmapW;
        case NW: return planeBitmapNW;
    }
    return planeBitmapN;
}

const uint8_t* small(Dir d) {
    // Diagonals snap to the cardinal they were rotated from - see the
    // header for why the small set only has four.
    switch (d) {
        case N:  case NE: return planeSmallN;
        case E:  case SE: return planeSmallE;
        case S:  case SW: return planeSmallS;
        case W:  case NW: return planeSmallW;
    }
    return planeSmallE;
}

void drawLarge(TFT_eSPI* tft, int x, int y, Dir d, uint16_t color) {
    tft->drawBitmap(x, y, large(d), LARGE_W, LARGE_H, color);
}

void drawSmall(TFT_eSPI* tft, int x, int y, Dir d, uint16_t color) {
    tft->drawBitmap(x, y, small(d), SMALL_W, SMALL_H, color);
}

void drawLargeCentered(TFT_eSPI* tft, int cx, int cy, Dir d, uint16_t color) {
    drawLarge(tft, cx - LARGE_W / 2, cy - LARGE_H / 2, d, color);
}

void drawSmallCentered(TFT_eSPI* tft, int cx, int cy, Dir d, uint16_t color) {
    drawSmall(tft, cx - SMALL_W / 2, cy - SMALL_H / 2, d, color);
}

